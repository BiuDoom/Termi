import Foundation

/// Renders the private ssh_config / known_hosts files for one master connection.
///
/// Every hop gets its own `Host` block with a unique alias, so a jump chain can mix users,
/// keys and passwords per machine (`ProxyJump` passes `-F` down to the jump-host ssh).
/// `HostKeyAlias` makes host-key lookups and password prompts refer to that alias.
enum SSHConfigRenderer {
    struct Files: Sendable, Equatable {
        var knownHostsPath: String
        /// Control socket of the master connection (destination block only).
        var controlPath: String
        /// alias → private key file written for that hop.
        var identityFiles: [String: String] = [:]
        /// App-private ssh-agent socket holding vault keys that should be forwarded.
        var agentSocketPath: String?
    }

    static func render(_ spec: SSHConnectionSpec, files: Files) -> String {
        var lines: [String] = [
            "# Generated by Termi — do not edit. Regenerated for every connection.",
        ]

        for (index, hop) in spec.hops.enumerated() {
            let isTarget = index == spec.hops.count - 1
            lines.append("")
            lines.append("Host \(hop.alias)")
            func option(_ name: String, _ value: String) { lines.append("  \(name) \(value)") }

            option("HostName", escapeTokens(hop.hostname))
            option("Port", String(hop.port))
            option("User", escapeTokens(hop.username))
            option("HostKeyAlias", hop.alias)
            option("UserKnownHostsFile", quote(escapeTokens(files.knownHostsPath)))
            option("GlobalKnownHostsFile", "/dev/null")
            option("StrictHostKeyChecking", "ask")
            option("CheckHostIP", "no")
            option("UpdateHostKeys", "no")
            option("HashKnownHosts", "no")
            option("VerifyHostKeyDNS", "no")
            // Behind a jump host the timeout keeps running while the user answers that jump
            // host's prompts (this hop's banner only arrives once the jump is authenticated).
            option("ConnectTimeout", String(index == 0 ? spec.connectTimeout : max(spec.connectTimeout, 120)))
            option("ServerAliveInterval", String(spec.keepAliveInterval))
            option("ServerAliveCountMax", String(spec.keepAliveCountMax))
            option("TCPKeepAlive", "yes")
            option("BatchMode", "no")
            option("PasswordAuthentication", "yes")
            option("KbdInteractiveAuthentication", "yes")
            option("NumberOfPasswordPrompts", "3")

            let credentials = hop.credentials
            if let keyPath = files.identityFiles[hop.alias], credentials.privateKey != nil {
                option("PubkeyAuthentication", "yes")
                option("IdentityFile", quote(escapeTokens(keyPath)))
                if !credentials.useSystemAgent {
                    option("IdentitiesOnly", "yes")
                }
                option("PreferredAuthentications", "publickey,keyboard-interactive,password")
            } else if credentials.useSystemAgent {
                option("PubkeyAuthentication", "yes")
                option("PreferredAuthentications", "publickey,keyboard-interactive,password")
            } else {
                option("PubkeyAuthentication", "no")
                option("PreferredAuthentications", "keyboard-interactive,password")
            }

            let forwardsAgent = isTarget && hop.agentForwarding
            if forwardsAgent, credentials.privateKey != nil, !credentials.useSystemAgent,
               let agentSocket = files.agentSocketPath {
                option("IdentityAgent", quote(escapeTokens(agentSocket)))
            } else if !credentials.useSystemAgent && !forwardsAgent {
                option("IdentityAgent", "none")
            }
            option("ForwardAgent", forwardsAgent ? "yes" : "no")
            option("ForwardX11", "no")
            option("AddKeysToAgent", "no")
            #if canImport(Darwin)
            // Apple's ssh: "UseKeychain yes" from an included user config would copy the
            // passphrases of vault keys into the macOS keychain. (No IgnoreUnknown for other
            // builds: it would replace the user's own IgnoreUnknown and break their config.)
            option("UseKeychain", "no")
            #endif

            if index == 0 {
                // "none" also blocks any ProxyCommand from an included user config.
                option("ProxyJump", "none")
            } else {
                option("ProxyJump", spec.hops[index - 1].alias)
            }

            option("ControlMaster", "no")
            if isTarget {
                option("ControlPath", quote(escapeTokens(files.controlPath)))
                option("SendEnv", "LANG LC_*")
            } else {
                option("ControlPath", "none")
            }
            option("ControlPersist", "no")
            option("PermitLocalCommand", "no")
            option("RemoteCommand", "none")
            option("RequestTTY", "auto")
            option("ExitOnForwardFailure", "no")
            option("LogLevel", "ERROR")
            // Only audited transport/algorithm options are inherited. Authentication, key
            // trust, commands, forwarding and connection reuse remain app-controlled.
            for name in hop.userOptions.keys.sorted() where inheritedOptionNames.contains(name) {
                if let value = hop.userOptions[name], isSafeOptionValue(value) {
                    option(name, value)
                }
            }
            // A hop that offers "the system SSH agent / ~/.ssh keys" gets them as plain ssh
            // would: the agent (1Password, Secretive…) and the key files the user's ssh_config
            // names for this host. Every other hop keeps IdentitiesOnly / IdentityAgent none.
            if credentials.useSystemAgent {
                let agent = hop.userAgentOptions
                if let identityAgent = agent.identityAgent {
                    if identityAgent == "none" || identityAgent == "SSH_AUTH_SOCK" {
                        option("IdentityAgent", identityAgent)
                    } else if isSafePath(identityAgent) {
                        option("IdentityAgent", quote(escapeTokens(identityAgent)))
                    }
                }
                if files.identityFiles[hop.alias] == nil || credentials.privateKey == nil {
                    for path in agent.identityFiles where isSafePath(path) {
                        option("IdentityFile", quote(escapeTokens(path)))
                    }
                    for path in agent.certificateFiles where isSafePath(path) {
                        option("CertificateFile", quote(escapeTokens(path)))
                    }
                }
            }
        }

        lines.append("")
        return lines.joined(separator: "\n")
    }

    /// Use OpenSSH itself for Host patterns, Include files and algorithm +/- modifiers.
    /// Running -G exits after config evaluation; no connection is opened. Values resolved
    /// against the internal aliases would miss the user's host-specific blocks.
    ///
    /// Only what the user's config changes is inherited: `-G` prints every option, set or not,
    /// and a value equal to OpenSSH's own default is left out. Written into the app's block it
    /// would count as set — and an explicit HostKeyAlgorithms, for one, stops OpenSSH from
    /// preferring the key types already in known_hosts, so a trusted server that gains a new
    /// key type would ask to be trusted again. (A "+" / "-" modifier in the user's config comes
    /// back expanded and is kept: the user changed that list.)
    static func resolvingUserOptions(in spec: SSHConnectionSpec) async throws -> SSHConnectionSpec {
        guard let path = spec.userConfigPath else { return spec }
        try spec.validate()
        let defaultsOutput = try await evaluate(["-G", "-F", "/dev/null", "-o", "CanonicalizeHostname=no",
                                                 "termi-defaults"])
        let defaults = inheritedOptions(from: defaultsOutput)
        let defaultAgent = agentOptions(from: defaultsOutput)
        var resolved = spec
        for index in resolved.hops.indices {
            try Task.checkCancellation()
            let hop = resolved.hops[index]
            let output = try await evaluate([
                "-G", "-F", path, "-o", "CanonicalizeHostname=no",
                "-o", "HostName=\(escapeTokens(hop.hostname))",
                "-l", hop.username, "-p", String(hop.port), hop.userConfigAlias ?? hop.hostname,
            ])
            resolved.hops[index].userOptions = inheritedOptions(from: output).filter { defaults[$0.key] != $0.value }
            var agent = agentOptions(from: output)
            if agent.identityAgent == defaultAgent.identityAgent { agent.identityAgent = nil }
            if agent.identityFiles == defaultAgent.identityFiles { agent.identityFiles = [] }
            if agent.certificateFiles == defaultAgent.certificateFiles { agent.certificateFiles = [] }
            resolved.hops[index].userAgentOptions = agent
        }
        return resolved
    }

    /// `ssh -G …`: evaluates the configuration and exits, without connecting.
    private static func evaluate(_ arguments: [String]) async throws -> String {
        let result = try await ProcessRunner.run("/usr/bin/ssh", arguments: arguments)
        try Task.checkCancellation()
        guard result.exitCode == 0 else {
            throw SSHError.invalidConfiguration(result.stderr.trimmingCharacters(in: .whitespacesAndNewlines))
        }
        return result.stdout
    }

    // Deliberately exclude IdentityFile, HostName/User/Port, ProxyCommand/Jump, trust files,
    // LocalCommand/RemoteCommand, agent settings and forwards (some accumulate despite
    // earlier values in ssh_config, so merely putting the app's block first is not enough).
    private static let inheritedOptionNames: Set<String> = [
        "ciphers", "macs", "kexalgorithms", "hostkeyalgorithms", "pubkeyacceptedalgorithms",
        "casignaturealgorithms", "compression", "rekeylimit", "ipqos", "addressfamily",
    ]

    static func inheritedOptions(from output: String) -> [String: String] {
        var options: [String: String] = [:]
        for line in output.split(whereSeparator: \.isNewline) {
            let fields = line.split(maxSplits: 1, whereSeparator: \.isWhitespace)
            guard fields.count == 2 else { continue }
            let name = fields[0].lowercased(), value = String(fields[1])
            if inheritedOptionNames.contains(name), isSafeOptionValue(value) { options[name] = value }
        }
        return options
    }

    /// IdentityAgent / IdentityFile / CertificateFile from `-G` output (IdentityFile and
    /// CertificateFile repeat; their order is kept).
    static func agentOptions(from output: String) -> SSHUserAgentOptions {
        var options = SSHUserAgentOptions()
        for line in output.split(whereSeparator: \.isNewline) {
            let fields = line.split(maxSplits: 1, whereSeparator: \.isWhitespace)
            guard fields.count == 2 else { continue }
            let value = String(fields[1])
            switch fields[0].lowercased() {
            case "identityagent": options.identityAgent = value
            case "identityfile": options.identityFiles.append(value)
            case "certificatefile": options.certificateFiles.append(value)
            default: break
            }
        }
        return options
    }

    /// A file path for a quoted ssh_config value: absolute or under "~/", no quote, backslash,
    /// control character or line break (spaces are fine: "Group Containers").
    static func isSafePath(_ value: String) -> Bool {
        guard value.hasPrefix("/") || value.hasPrefix("~/") else { return false }
        return !value.unicodeScalars.contains { scalar in
            CharacterSet.controlCharacters.contains(scalar) || CharacterSet.newlines.contains(scalar)
                || scalar == "\"" || scalar == "\\"
        }
    }

    private static func isSafeOptionValue(_ value: String) -> Bool {
        !value.isEmpty && value.unicodeScalars.allSatisfy {
            CharacterSet(charactersIn: "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_,.@/ ").contains($0)
        }
    }

    /// known_hosts content: every trusted key recorded under the hop alias (see `HostKeyAlias`).
    static func knownHosts(for spec: SSHConnectionSpec) -> String {
        var lines: [String] = []
        for hop in spec.hops {
            for key in hop.knownHostKeys {
                let parts = key.split(separator: " ", omittingEmptySubsequences: true)
                guard parts.count >= 2 else { continue }
                lines.append("\(hop.alias) \(parts[0]) \(parts[1])")
            }
        }
        return lines.isEmpty ? "" : lines.joined(separator: "\n") + "\n"
    }

    /// Parse known_hosts lines written by ssh (after the user trusted a new key).
    /// Returns (alias, "keytype base64") pairs.
    static func parseKnownHosts(_ content: String) -> [(alias: String, key: String)] {
        content.split(whereSeparator: \.isNewline).compactMap { rawLine in
            let line = rawLine.trimmingCharacters(in: .whitespaces)
            guard !line.isEmpty, !line.hasPrefix("#"), !line.hasPrefix("@") else { return nil }
            let parts = line.split(separator: " ", omittingEmptySubsequences: true)
            guard parts.count >= 3 else { return nil }
            // The host field may list several comma-separated names; ours is a single alias.
            let alias = String(parts[0].split(separator: ",").first ?? parts[0])
            return (alias, "\(parts[1]) \(parts[2])")
        }
    }

    /// Double-quote a value for ssh_config (values never contain quotes — see `isSafeValue`).
    static func quote(_ value: String) -> String {
        "\"\(value)\""
    }

    /// `%` introduces tokens (%h, %p…) in several ssh_config options.
    static func escapeTokens(_ value: String) -> String {
        value.replacingOccurrences(of: "%", with: "%%")
    }
}
