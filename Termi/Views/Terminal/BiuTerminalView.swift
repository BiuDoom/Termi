import AppKit
import SwiftTerm

/// SwiftTerm terminal view with the hooks Termi needs:
/// - tees received bytes (session logs, startup snippet timing)
/// - reports user input separately from the terminal's own replies (for broadcast input)
/// - reports clicks (pane focus), copy-on-select and a context menu
final class BiuTerminalView: LocalProcessTerminalView {
    var onDataReceived: ((ArraySlice<UInt8>) -> Void)?
    /// Keystrokes / pastes typed by the user (never escape-sequence replies from the terminal).
    var onUserInput: ((ArraySlice<UInt8>) -> Void)?
    var onFocus: (() -> Void)?
    var copyOnSelect = false
    var contextMenuProvider: (() -> NSMenu?)?

    private var isRelayingTerminalReply = false
    /// SwiftTerm's find bar once it exists (it is created on first use and then only hidden).
    private weak var findBarView: NSView?

    /// SwiftTerm's own scroller (private there), found among the subviews on first use.
    private weak var scrollerView: NSScroller?

    /// With nothing to scroll back to, the scroller is not drawn at all. SwiftTerm only
    /// disables it then, and a disabled overlay scroller is not always invisible: one that
    /// joins a window already on screen (the fresh view of a reconnect) kept a faint track at
    /// the pane's edge that a pane created with its window never had. Its width stays
    /// reserved either way — the grid does not change.
    override func viewWillDraw() {
        super.viewWillDraw()
        if scrollerView == nil {
            scrollerView = subviews.lazy.compactMap { $0 as? NSScroller }.first
        }
        guard let scrollerView else { return }
        let alpha: CGFloat = scrollerView.isEnabled ? 1 : 0
        if scrollerView.alphaValue != alpha {
            scrollerView.alphaValue = alpha
        }
    }

    override func dataReceived(slice: ArraySlice<UInt8>) {
        onDataReceived?(slice)
        super.dataReceived(slice: slice)
    }

    /// Replies generated by the terminal emulator itself (cursor position reports, DA…).
    override func send(source: Terminal, data: ArraySlice<UInt8>) {
        isRelayingTerminalReply = true
        defer { isRelayingTerminalReply = false }
        super.send(source: source, data: data)
    }

    override func send(source: TerminalView, data: ArraySlice<UInt8>) {
        super.send(source: source, data: data)
        if !isRelayingTerminalReply {
            onUserInput?(data)
        }
    }

    /// Write bytes straight to the process, bypassing input hooks (used for broadcast targets).
    func sendToProcess(_ bytes: ArraySlice<UInt8>) {
        guard process?.running == true else { return }
        process.send(data: bytes)
    }

    /// Stop the child process and reap it. SwiftTerm's `terminate()` alone only sends SIGTERM,
    /// which interactive shells ignore, and stops watching the child: a local shell would keep
    /// running and an ssh client would stay behind as a zombie.
    func terminateAndReap() {
        // `shellPid` is stale once the process has ended — never signal it then.
        guard process?.running == true, let pid = process?.shellPid, pid > 0 else { return }
        terminate()
        kill(pid, SIGHUP)
        // @Sendable: runs on a background queue, must not inherit this view's MainActor isolation.
        DispatchQueue.global(qos: .utility).async { @Sendable in
            // Reap it once it exits; SIGKILL after 2 s. Never wait unbounded: a process stuck
            // flushing its pty ignores even SIGKILL and would pin this thread forever.
            var status: Int32 = 0
            for attempt in 0..<40 {
                if waitpid(pid, &status, WNOHANG) != 0 { return }
                if attempt == 20 { kill(pid, SIGKILL) }
                usleep(100_000)
            }
        }
    }

    override func mouseDown(with event: NSEvent) {
        onFocus?()
        super.mouseDown(with: event)
    }

    override func mouseUp(with event: NSEvent) {
        super.mouseUp(with: event)
        if copyOnSelect, selection.active {
            let text = selection.getSelectedText()
            if !text.isEmpty {
                NSPasteboard.general.clearContents()
                NSPasteboard.general.setString(text, forType: .string)
            }
        }
    }

    override func menu(for event: NSEvent) -> NSMenu? {
        onFocus?()
        return contextMenuProvider?() ?? super.menu(for: event)
    }

    // MARK: - Find

    func showFindBar() {
        performFindPanelAction(Self.findMenuItem(.showFindPanel))
        localizeFindBar()
    }

    /// SwiftTerm's find bar is English only and not public API: its controls are reached through
    /// the view tree and recognised by the English text SwiftTerm gives them. A control that is
    /// not recognised stays as it is.
    private func localizeFindBar() {
        guard let bar = subviews.first(where: { String(describing: type(of: $0)).contains("FindBar") }) else { return }
        adoptFindBar(bar)
        let tooltips = [
            "Previous": String(localized: "Previous Match"),
            "Next": String(localized: "Next Match"),
            "Close": String(localized: "Close"),
            "Case Sensitive": String(localized: "Match Case"),
            "Regex": String(localized: "Regular Expression"),
            "Whole Word": String(localized: "Whole Word")
        ]
        var pending: [NSView] = [bar]
        while let view = pending.popLast() {
            pending.append(contentsOf: view.subviews)
            if let field = view as? NSSearchField, field.placeholderString == "Find" {
                field.placeholderString = String(localized: "Find")
            } else if let button = view as? NSButton, let tooltip = button.toolTip, let text = tooltips[tooltip] {
                button.toolTip = text
                button.setAccessibilityLabel(text)
                // The only option whose label is a word; "Aa" and ".*" need no translation.
                if button.title == "Word" { button.title = String(localized: "Word") }
            }
        }
    }

    /// SwiftTerm pins its bar inside the terminal with required constraints (8 pt from the
    /// leading edge, a search field of 200 pt). In a pane narrower than about 440 pt they made
    /// the terminal itself wider than its pane, and it stayed so after the bar was closed: the
    /// text ran under the neighbouring pane, the sidebar or the inspector. The bar is placed by
    /// frame instead, so nothing inside the terminal can ask for a size.
    private func adoptFindBar(_ bar: NSView) {
        if findBarView !== bar {
            NSLayoutConstraint.deactivate(constraints.filter { $0.firstItem === bar || $0.secondItem === bar })
            bar.translatesAutoresizingMaskIntoConstraints = true
            bar.autoresizingMask = []
            var pending: [NSView] = [bar]
            while let view = pending.popLast() {
                pending.append(contentsOf: view.subviews)
                guard view is NSSearchField else { continue }
                for constraint in view.constraints where constraint.priority == .required
                    && constraint.firstItem === view && constraint.firstAttribute == .width
                    && constraint.relation == .greaterThanOrEqual {
                    constraint.isActive = false
                    constraint.priority = NSLayoutConstraint.Priority(500)
                    constraint.isActive = true
                }
            }
            findBarView = bar
        }
        placeFindBar()
    }

    /// Top trailing corner, 8 pt in, at most 520 pt wide (SwiftTerm's own figures).
    private func placeFindBar() {
        guard let bar = findBarView else { return }
        let width = max(0, min(520, bounds.width - 16))
        let height = max(30, bar.fittingSize.height)
        bar.frame = NSRect(x: bounds.maxX - 8 - width, y: isFlipped ? 8 : bounds.maxY - 8 - height,
                           width: width, height: height)
    }

    override func setFrameSize(_ newSize: NSSize) {
        super.setFrameSize(newSize)
        placeFindBar()
    }

    func findNext() {
        performFindPanelAction(Self.findMenuItem(.next))
    }

    func findPrevious() {
        performFindPanelAction(Self.findMenuItem(.previous))
    }

    private static func findMenuItem(_ action: NSFindPanelAction) -> NSMenuItem {
        let item = NSMenuItem()
        item.tag = Int(action.rawValue)
        return item
    }

    var hasSelection: Bool {
        selection.active
    }

    func copySelection() {
        copy(self)
    }

    func pasteClipboard() {
        paste(self)
    }

    /// Clear the screen and scrollback, then let the shell redraw its prompt (Ctrl-L).
    func clearBuffer() {
        feed(text: "\u{1B}[H\u{1B}[2J\u{1B}[3J")
        sendToProcess(ArraySlice([0x0C]))
    }
}

/// NSMenuItem that runs a closure.
final class BlockMenuItem: NSMenuItem {
    private let handler: () -> Void

    init(_ title: String, keyEquivalent: String = "", enabled: Bool = true, handler: @escaping () -> Void) {
        self.handler = handler
        super.init(title: title, action: #selector(run), keyEquivalent: keyEquivalent)
        target = self
        isEnabled = enabled
    }

    required init(coder: NSCoder) {
        fatalError("init(coder:) is not supported")
    }

    @objc private func run() {
        handler()
    }
}
